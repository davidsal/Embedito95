const UNKNOWN_PLATFORM_LABEL = "unknown";

export const buildAgentsDocument = ({ platform }) => {
	const platformLabel = platform
		? `${platform.displayName} (\`${platform.name}\`)`
		: UNKNOWN_PLATFORM_LABEL;

	return `# AGENTS.md

Instructions for AI agents working in this project.

## What this project is

An **Embedito95** project written in **e95**, a small TypeScript-like language
that compiles to C++ and runs on microcontrollers. It targets **${platformLabel}**.

The whole toolchain is the \`embedito95-cli\` command, run with
\`npx embedito95-cli <command>\` or, after a global install,
\`embedito95 <command>\`.

## Before writing any code

Read \`docs/e95-language.md\` first. It is short: design, the "Coming from
TypeScript" table, keywords and a map of topic files. **e95 is not TypeScript.**

Then open only the topic file for what you are writing: declarations, types,
expressions, control flow or async. Do not read the whole \`docs/language/\`
directory.

## Libraries

Core libraries are installed under \`core/\` and are always available.
Built-in libraries are added with \`npx embedito95-cli install <name>\`.
Run \`npx embedito95-cli libraries\` to see what is available and what is
installed.

The index is \`docs/libraries.md\`. The exact API of a library is its
\`main.e95\`.

## Other docs

Read only what the task needs:

| Task | Read |
| --- | --- |
| Running a command | \`docs/cli.md\`, section for that command. |
| Pins, peripherals or board limits | \`docs/boards.md\`. |
| Memory, tasks or references | \`docs/engine.md\`. |

The full docs are versioned together in \`docs/\`. \`docs/VERSION\` holds the same
version as \`embedito95Version\` in \`config.json\`, which adds the
\`embedito95@\` prefix.

## Project layout

\`\`\`text
config.json          project name, platform, toolchain version, installed libraries
main.e95             entry point; the program starts at main()
core/<library>/       core libraries installed for this platform
libraries/<library>/  project libraries and libraries added with install
docs/                 documentation for this toolchain version
build/                generated output (ignore it, never edit it)
\`\`\`

## Library documentation lives in the project

Every installed library has a \`main.e95\` that declares its exported types,
constants, enums and function signatures with doc comments. **That file is the
documentation for your version.** Read it before using a library:

\`\`\`text
core/gpio/main.e95        exported API of @embedito95/gpio
core/gpio/build/*.h       generated C++ header (when the library has one)
libraries/dht22/main.e95  API of an installed library
\`\`\`

- Never edit \`core/\` or \`build/\`. Both are regenerated by \`install\` and
  \`build\`.
- \`docs/libraries.md\` gives prose and examples; \`main.e95\` gives the exact
  signatures shipped with this project. If they disagree, trust \`main.e95\`.
- On a fresh clone \`core/\` is absent because it is generated. Run
  \`npx embedito95-cli install\` before reading it.
`;
};
